var (
	mu     sync.Mutex
	counts = map[string]int64{}
)

func add(p *demoinfocs.Parser, name string, ft reflect.Type) {
	fn := reflect.MakeFunc(ft, func(in []reflect.Value) []reflect.Value {
		mu.Lock()
		counts[name]++
		mu.Unlock()
		return nil
	})
	p.RegisterNetMessageHandler(fn.Interface())
}

