func main() {
	path := "/tmp/opencode/donk.dem"
	if len(os.Args) > 1 {
		path = os.Args[1]
	}
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	p := demoinfocs.NewParser(f,
		option.IgnorePacketEntitiesPanic(true),
		option.MsgQueueBufferSize(0),
	)
	defer p.Close()

	registerAll(p)

	if err := p.ParseToEnd(context.Background()); err != nil {
		fmt.Println("parse note:", err)
	}

	type row struct {
		name  string
		count int64
	}
	var rows []row
	for k, v := range counts {
		rows = append(rows, row{k, v})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].count > rows[j].count })
	total := int64(0)
	for _, r := range rows {
		total += r.count
	}
	fmt.Printf("firing types: %d  total messages: %d\n", len(rows), total)
	for _, r := range rows {
		fmt.Printf("%8d  %s\n", r.count, r.name)
	}
}
