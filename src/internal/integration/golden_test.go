// shouldSkip reports whether the golden demo at path is unusable (absent or
// an un-smudged Git LFS pointer), with a human-readable reason.
func shouldSkip(path string) (bool, string) {
	fi, err := os.Stat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return true, "golden demo missing (shallow clone or LFS not pulled)"
		}
		return true, fmt.Sprintf("stat golden demo: %v", err)
	}
	if fi.Size() < lfsPointerMaxSize {
		// Safe to slurp: only tiny files reach here.
		data, err := os.ReadFile(path) //nolint:gosec // path is the fixed demo location or a unit-test temp file
		if err != nil {
			return true, fmt.Sprintf("read golden demo: %v", err)
		}
		first, _, _ := strings.Cut(string(data), "\n")
		if strings.HasPrefix(strings.TrimRight(first, "\r"), lfsPointerPrefix) {
			return true, "golden demo is a Git LFS pointer (run git lfs pull)"
		}
	}
	return false, ""
}

// TestGoldenSkipBehavior unit-tests the pointer/absent detection without a
// demo file (no LFS requirement, runs under -short).
func TestGoldenSkipBehavior(t *testing.T) {
	t.Run("missing", func(t *testing.T) {
		skip, reason := shouldSkip(filepath.Join(t.TempDir(), "nope.dem.zst"))
		if !skip {
			t.Error("missing file: skip = false, want true")
		}
		if reason == "" {
			t.Error("missing file: empty skip reason")
		}
	})

	t.Run("lfs pointer", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "pointer.dem.zst")
		pointer := lfsPointerPrefix + "/v1\noid sha256:0123456789abcdef\nsize 189897437\n"
		if err := os.WriteFile(path, []byte(pointer), 0o600); err != nil {
			t.Fatalf("write pointer file: %v", err)
		}
		skip, reason := shouldSkip(path)
		if !skip {
			t.Error("LFS pointer: skip = false, want true")
		}
		if !strings.Contains(reason, "LFS pointer") {
			t.Errorf("LFS pointer: reason = %q, want mention of LFS pointer", reason)
		}
	})

	t.Run("large fake file is not skipped", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "fake.dem.zst")
		if err := os.WriteFile(path, bytes.Repeat([]byte{0x42}, lfsPointerMaxSize+1), 0o600); err != nil {
			t.Fatalf("write fake file: %v", err)
		}
		if skip, reason := shouldSkip(path); skip {
			t.Errorf("file >4KB: skip = true (reason %q), want false", reason)
		}
	})

	t.Run("small non-pointer file is not skipped", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "tiny.dem")
		if err := os.WriteFile(path, []byte("PBDEMS2 not an lfs pointer\n"), 0o600); err != nil {
			t.Fatalf("write tiny file: %v", err)
		}
		if skip, reason := shouldSkip(path); skip {
			t.Errorf("small non-pointer: skip = true (reason %q), want false", reason)
		}
	})
}

// countingVoiceSink tallies the CSVCMsg_VoiceData stream for the fixture
// (chunks / distinct XUIDs / caster chunks) and records the first delivered
// chunk's tick for the sanitization-boundary pin (owner ruling, 2026-11-12:
// no chunk below the first counted round's startTick may reach a sink).
type countingVoiceSink struct {
	chunks  int
	xuids   map[uint64]bool
	casts   int
	minTick int
	minSet  bool
}

func (s *countingVoiceSink) Add(c extract.VoiceChunk) error {
	if s.xuids == nil {
		s.xuids = map[uint64]bool{}
	}
	s.chunks++
	s.xuids[c.XUID] = true
	if c.Caster {
		s.casts++
	}
	if !s.minSet || c.Tick < s.minTick {
		s.minTick = c.Tick
		s.minSet = true
	}
	return nil
}

func (s *countingVoiceSink) fixture() goldenVoice {
	return goldenVoice{Chunks: s.chunks, XUIDs: len(s.xuids), Casters: s.casts}
}

// TestGolden is the Tier-1 acceptance check against the committed fixture.
// Skipped under -short and when the demo is absent or an LFS pointer so
// `make test` never hard-fails on missing LFS content.
func TestGolden(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping golden-demo parse in -short mode")
	}
	if skip, reason := shouldSkip(demoPath); skip {
		t.Skip(reason)
	}

	f, err := os.Open(demoPath) //nolint:gosec // path is the fixed repo-root golden demo
	if err != nil {
		t.Fatalf("open golden demo: %v", err)
	}
	defer func() { _ = f.Close() }()

	// Magic sniff: zstd frame magic → decompress with klauspost; else raw .dem.
	head := make([]byte, len(zstdMagic))
	if _, err := io.ReadFull(f, head); err != nil {
		t.Fatalf("sniff demo magic: %v", err)
	}
	// Re-feed the sniffed bytes so the consumer always sees the full stream.
	reader := io.MultiReader(bytes.NewReader(head), f)
	if bytes.Equal(head, zstdMagic[:]) {
		zr, zerr := zstd.NewReader(reader)
		if zerr != nil {
			t.Fatalf("zstd.NewReader: %v", zerr)
		}
		defer zr.Close()
		reader = zr
	}

	start := time.Now()
	// The clutch SQL reads player_ticks, so the golden parse streams the tick
	// table into the store the analytics pass runs on.
	gst, err := store.Open(filepath.Join(t.TempDir(), "golden.db"))
	if err != nil {
		t.Fatalf("open analytics store: %v", err)
	}
	defer func() { _ = gst.Close() }()
	gid, err := gst.CreateMatchRow("golden-demo", "sha-golden-analytics", 0)
	if err != nil {
		t.Fatalf("CreateMatchRow: %v", err)
	}
	tw, err := gst.NewTickWriter(gid)
	if err != nil {
		t.Fatalf("NewTickWriter: %v", err)
	}
	voice := &countingVoiceSink{}
	m, err := extract.Parse(context.Background(), reader, extract.ParseOptions{Voice: voice, Ticks: tw})
	parseSeconds := time.Since(start).Seconds()
	if err != nil {
		t.Fatalf("extract.Parse: %v", err)
	}
	if m == nil {
		t.Fatal("extract.Parse returned nil ExtractedMatch")
	}
	if err := tw.Close(); err != nil {
		t.Fatalf("TickWriter.Close: %v", err)
	}
	t.Logf("parsed golden/de_cache.dem.zst in %.1fs (%d voice chunks)", parseSeconds, voice.chunks)

	// ---- sanitization boundary (owner ruling, 2026-11-12) ----
	// No voice chunk below the FIRST COUNTED round's startTick may reach
	// the sink (extract.Parse's gate); the earliest delivered chunk must
	// therefore sit at or after the boundary.
	if len(m.Rounds) == 0 {
		t.Fatal("no counted rounds")
	}
	voiceBoundary := m.Rounds[0].StartTick
	if voice.minSet && voice.minTick < voiceBoundary {
		t.Errorf("first voice chunk tick = %d, below the first counted round's startTick %d", voice.minTick, voiceBoundary)
	}
	t.Logf("first voice chunk tick = %d (first counted round startTick %d)", voice.minTick, voiceBoundary)

	// Both known demos carry 0 svc_EncryptedData messages —
	// the encrypted-chat path stays synthetic-only until a Valve MM demo
	// with a .info companion appears.
	if m.Match.EncryptedMessages != 0 {
		t.Errorf("enc_messages = %d, want 0 (golden demo baseline)", m.Match.EncryptedMessages)
	}

	got := buildGolden(t, m, voice)
	if parseSeconds > parseSecondsMax {
		t.Errorf("parse wall-time %.1fs exceeds ceiling %ds (fixture records the ceiling, not the measurement)",
			parseSeconds, parseSecondsMax)
	}

	// Hard-coded safety nets: asserted ALWAYS, even with -update, so a bad
	// regeneration cannot silently commit a shifted baseline.
	assertSafetyNets(t, &got)

	// Chat channel capture (SayText2 MsgName): the golden pool carries ONLY
	// all-chat MsgNames (Cstrike_Chat_All/_AllDead — golden-pool MsgName
	// census), so every chat row must be kind "chat" with channel "all".
	// Together with the fixture's chat count this is also the
	// no-duplication pin: exactly one row per SayText2 message — a second
	// consumer (the removed events.ChatMessage handler) would double both.
	for i, c := range m.Chat {
		if c.Kind != "chat" || c.Channel != "all" {
			t.Errorf("chat[%d] kind/channel = %q/%q, want chat/all", i, c.Kind, c.Channel)
		}
	}

	// Detonation no-duplication pin (bug class, not one number): exactly
	// ONE stored detonation row per (tick, thrower, weapon) — demoinfocs
	// v6 dispatches FlashExplode twice per flashbang (CS2.md "A flashbang
	// detonation fires TWICE in demoinfocs-golang v6") and the extractor's
	// agg.blastSeen dedupe keeps the first dispatch. Count-free: it stays
	// green through any fixture regen.
	type blastKey struct {
		tick     int
		attacker string
		weapon   string
	}
	blastSeen := map[blastKey]int{}
	for _, e := range m.Events {
		if e.Kind != models.EventGrenade {
			continue
		}
		k := blastKey{tick: e.Tick, attacker: e.Attacker, weapon: e.Weapon}
		blastSeen[k]++
		if blastSeen[k] == 2 {
			t.Errorf("duplicate EventGrenade rows at (tick %d, thrower %q, weapon %q) — one detonation must store one row",
				e.Tick, e.Attacker, e.Weapon)
		}
	}

	// M3 analytics pass over the same extract (always — its safety nets
	// hold in both update and verify mode).
	gotAnalytics := runGoldenAnalytics(t, m, gst, gid)

	if *update {
		if err := os.MkdirAll(filepath.Dir(fixturePath), 0o755); err != nil {
			t.Fatalf("mkdir testdata: %v", err)
		}
		data, err := json.MarshalIndent(got, "", "  ")
		if err != nil {
			t.Fatalf("marshal fixture: %v", err)
		}
		if err := os.WriteFile(fixturePath, append(data, '\n'), 0o644); err != nil {
			t.Fatalf("write fixture: %v", err)
		}
		t.Logf("updated %s", fixturePath)
		adata, err := json.MarshalIndent(gotAnalytics, "", "  ")
		if err != nil {
			t.Fatalf("marshal analytics fixture: %v", err)
		}
		if err := os.WriteFile(analyticsFixturePath, append(adata, '\n'), 0o644); err != nil {
			t.Fatalf("write analytics fixture: %v", err)
		}
		t.Logf("updated %s", analyticsFixturePath)
		return
	}

	data, err := os.ReadFile(fixturePath) //nolint:gosec // fixed package-relative fixture path
	if err != nil {
		t.Fatalf("fixture %s unreadable (%v) — run: go test ./internal/integration -run TestGolden -update", fixturePath, err)
	}
	var want goldenFixture
	if err := json.Unmarshal(data, &want); err != nil {
		t.Fatalf("parse fixture %s: %v", fixturePath, err)
	}
	compareGolden(t, &got, &want)

	adata, err := os.ReadFile(analyticsFixturePath) //nolint:gosec // fixed package-relative fixture path
	if err != nil {
		t.Fatalf("fixture %s unreadable (%v) — run: go test ./internal/integration -run TestGolden -update", analyticsFixturePath, err)
	}
	var wantAnalytics analyticsFixture
	if err := json.Unmarshal(adata, &wantAnalytics); err != nil {
		t.Fatalf("parse fixture %s: %v", analyticsFixturePath, err)
	}
	compareAnalyticsGolden(t, &gotAnalytics, &wantAnalytics)
}

