// runGoldenAnalytics stores the parsed demo through the real pipeline
// (CreateMatchRow → SaveExtracted → analytics.Compute with default rules),
// logs the analytics wall-time and projects the stored rows onto the
// fixture shape. Hard safety nets always run.
func runGoldenAnalytics(t *testing.T, m *models.ExtractedMatch, st *store.Store, id int64) analyticsFixture {
	t.Helper()
	if err := st.SaveExtracted(id, m); err != nil {
		t.Fatalf("SaveExtracted: %v", err)
	}
	cfg := analytics.ConfigFrom(models.AnalysisConfig{
		TradeWindowS: 5.0, EcoFullBuy: 20000, EcoForce: 10000,
		TradeOppDistance: store.DefaultConfig.TradeOppDistance, RuleVersion: 1,
	}, 0)
	start := time.Now()
	if err := analytics.Compute(st, id, cfg); err != nil {
		t.Fatalf("analytics.Compute: %v", err)
	}
	analyticsSeconds := time.Since(start).Seconds()
	t.Logf("analytics pass on golden demo in %.2fs", analyticsSeconds)
	if analyticsSeconds > 10 {
		t.Errorf("analytics pass %.2fs exceeds the 10s budget", analyticsSeconds)
	}

	clutches, err := st.ClutchRows(id)
	if err != nil {
		t.Fatalf("ClutchRows: %v", err)
	}
	clutchWins := 0
	for _, c := range clutches {
		if c.Won {
			clutchWins++
		}
	}

	prs, err := st.GetPlayerRounds(id, "")
	if err != nil {
		t.Fatalf("GetPlayerRounds: %v", err)
	}
	kastTrue := 0
	for _, r := range prs {
		if r.KAST {
			kastTrue++
		}
	}
	var kastPctAvg float64
	if len(prs) > 0 {
		kastPctAvg = 100 * float64(kastTrue) / float64(len(prs))
	}

	// Money-column hard safety nets (owner ruling 2026-11-18): the
	// round-end prop samples must reach player_round_stats as REAL
	// values on the golden demo. Round 1 and round 13 are the two pistol
	// rounds — the game resets every player's account to $800 there
	// (m_iStartAccount carries the reset) and nobody has carried gear
	// beyond the free spawn pistol ($200 equipment value), both verified
	// by extract.TestDiagRoundMoneyProps on this demo. At least one
	// player must have spent money in round 1 (pistol buys). Runs even
	// with -update.
	pistolMoney := map[int]int{} // round → distinct money_start values
	pistolEquip := map[int]int{} // round → distinct equip values
	round1Spent := 0
	for _, r := range prs {
		if r.Round == 1 || r.Round == 13 {
			pistolMoney[r.Round*100000+r.MoneyStart] = 1
			pistolEquip[r.Round*100000+r.Equip] = 1
			if r.Round == 1 {
				round1Spent += r.Spent
			}
		}
	}
	if len(pistolMoney) != 2 {
		t.Errorf("pistol-round money_start values = %v, want exactly {1: 800, 13: 800} (the game's $800 reset)", pistolMoney)
	}
	for k := range pistolMoney {
		if k%100000 != 800 {
			t.Errorf("pistol-round money_start = %d, want 800", k%100000)
		}
	}
	if len(pistolEquip) != 2 {
		t.Errorf("pistol-round equip values = %v, want exactly {1: 200, 13: 200} (free spawn pistol only)", pistolEquip)
	}
	for k := range pistolEquip {
		if k%100000 != 200 {
			t.Errorf("pistol-round equip = %d, want 200 (the free spawn pistol's equipment value)", k%100000)
		}
	}
	if round1Spent <= 0 {
		t.Errorf("round 1 total spent = %d, want > 0 (pistol buys are recorded)", round1Spent)
	}

	classes, err := st.GetRoundClasses(id)
	if err != nil {
		t.Fatalf("GetRoundClasses: %v", err)
	}
	classCounts := map[string]int{"full": 0, "force": 0, "eco": 0, "save": 0, "pistol": 0}
	for _, c := range classes {
		if _, ok := classCounts[c.Label]; !ok {
			t.Errorf("unexpected classification label %q (round %d: %s)", c.Label, c.Round, c.Explanation)
			continue
		}
		classCounts[c.Label]++
	}

	engs, err := st.GetKillTags(id, "")
	if err != nil {
		t.Fatalf("GetKillTags: %v", err)
	}
	killTagsByKind := map[string]int{"opening": 0, "trade": 0, "traded": 0, "untraded": 0}
	for _, e := range engs {
		if _, ok := killTagsByKind[e.Kind]; !ok {
			t.Errorf("unexpected kill tag kind %q", e.Kind)
			continue
		}
		killTagsByKind[e.Kind]++
	}

	utils, err := st.GetUtility(id)
	if err != nil {
		t.Fatalf("GetUtility: %v", err)
	}

	// Utility no-duplication pin (bug class, not one number): no two
	// utility_events rows share (round, tick, thrower, kind) — each stored
	// detonation must yield exactly one utility row (the extractor's
	// agg.blastSeen dedupe, CS2.md "A flashbang detonation fires TWICE in
	// demoinfocs-golang v6"). Count-free: green through any fixture regen.
	type utilKey struct {
		round   int
		tick    int
		thrower string
		kind    string
	}
	utilSeen := map[utilKey]int{}
	for _, u := range utils {
		k := utilKey{round: u.Round, tick: u.Tick, thrower: u.Thrower, kind: u.Kind}
		utilSeen[k]++
		if utilSeen[k] == 2 {
			t.Errorf("duplicate utility rows at (round %d, tick %d, thrower %q, kind %q) — one detonation must yield one utility row",
				u.Round, u.Tick, u.Thrower, u.Kind)
		}
	}
	economy, err := st.GetEconomy(id)
	if err != nil {
		t.Fatalf("GetEconomy: %v", err)
	}

	// Item-11 pin: equip + unspent money − free spawn-issued default
	// pistols (the free_pistol_value COLUMN's round-trip property, not
	// the chart's net worth — the chart plots equip + cash and reads
	// 4600/5000 on round 1, 5000/4800 on round 13; CS2.md "Free
	// spawn-issued default pistol") must read EXACTLY the starting money
	// ($4000 = 5 × $800) for both sides of every pistol round: sides
	// hold a different number of free spawn pistols at freeze end.
	pistolRounds := 0
	for _, r := range economy {
		if r.Label != "pistol" {
			continue
		}
		pistolRounds++
		netCT := r.EquipCT + r.MoneyCT - r.FreePistolCT
		netT := r.EquipT + r.MoneyT - r.FreePistolT
		if netCT != 4000 || netT != 4000 {
			t.Errorf("pistol round %d equip+money−free = CT %d / T %d, want 4000/4000 (free-pistol column round-trip)",
				r.Round, netCT, netT)
		}
	}
	if pistolRounds != 2 {
		t.Errorf("pistol rounds in economy view = %d, want 2 (rounds 1 and 13)", pistolRounds)
	}

	// Hard safety nets: ALWAYS, even with -update.
	if len(clutches) == 0 {
		t.Error("safety: clutches = 0, want > 0 (clutch v2 must find 1vN records)")
	}
	if len(utils) == 0 {
		t.Error("safety: utilityRows = 0, want > 0")
	}
	if kastPctAvg < 0 || kastPctAvg > 100 {
		t.Errorf("safety: kastPctAvg = %v, want within 0..100", kastPctAvg)
	}

	return analyticsFixture{
		Clutches:        len(clutches),
		ClutchWins:      clutchWins,
		KASTPctAvg:      math.Round(kastPctAvg*100) / 100,
		ClassCounts:     classCounts,
		KillTagsByKind:  killTagsByKind,
		UtilityRows:     len(utils),
		PlayerRoundRows: len(prs),
		EconomyRows:     len(economy),
	}
}

