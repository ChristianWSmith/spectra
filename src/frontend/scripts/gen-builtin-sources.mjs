// Generates src/lib/builtins/generated/sources.js: the Svelte source text of
// every compiled builtin panel.
//
// A builtin panel is a .svelte file the bundler compiles. Its source text is
// embedded here so the Component builder can show it, and so an edit of it can
// be checked by the same save gate as a user component. The generator reads
// the registry (builtins/panels.js: BUILTIN_PANELS, its imports and the id
// constants) to map each builtin id to its .svelte file, so the registry stays
// the one place a builtin is declared. Nothing here is hand-maintained.
//
// Run by the build (`npm run build`, `npm run dev`); the output is gitignored.
// Usage: node scripts/gen-builtin-sources.mjs            (writes the module)
// The test suite imports generate() to check the written file is current.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const FRONTEND = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BUILTINS = join(FRONTEND, 'src', 'lib', 'builtins');
const PANELS_JS = join(BUILTINS, 'panels.js');
export const OUT_FILE = join(BUILTINS, 'generated', 'sources.js');

// panelRegistry parses panels.js into [{id, file}] — the id of each
// BUILTIN_PANELS entry and the .svelte file its component is imported from.
// The shapes it accepts are the ones panels.js uses: `export const X = '…'`
// id constants, `import Name from './x.svelte'`, and `KEY: Name,` entries in
// the BUILTIN_PANELS object (KEY a literal or a [CONST] reference).
export function panelRegistry(src) {
  const consts = new Map();
  for (const m of src.matchAll(/export const (\w+) = '([^']+)';/g)) consts.set(m[1], m[2]);
  const imports = new Map();
  for (const m of src.matchAll(/import (\w+) from '(\.\/[^']+\.svelte)';/g)) imports.set(m[1], m[2]);
  const start = src.indexOf('export const BUILTIN_PANELS = Object.freeze({');
  if (start < 0) throw new Error('panels.js: BUILTIN_PANELS not found');
  const end = src.indexOf('});', start);
  const body = src.slice(start, end);
  const out = [];
  for (const m of body.matchAll(/^\s*(\[(\w+)\]|'([^']+)'):\s*(\w+),?\s*$/gm)) {
    const id = m[2] ? consts.get(m[2]) : m[3];
    if (!id) throw new Error(`panels.js: no id constant for ${m[2]}`);
    const file = imports.get(m[4]);
    if (!file) throw new Error(`panels.js: ${m[4]} is not imported from a .svelte file`);
    out.push({ id, file });
  }
  if (out.length === 0) throw new Error('panels.js: BUILTIN_PANELS has no entries');
  return out;
}

// generate returns the module text for the given frontend root (defaults to
// this checkout). Sources are JSON-encoded string literals, so no template
// escaping is ever needed.
export function generate(root = FRONTEND) {
  const dir = join(root, 'src', 'lib', 'builtins');
  // The placeholder example: a Svelte file the Builder shows as a sample (not a
  // compiled panel, so it is not in the registry).
  const placeholder = readFileSync(join(root, 'src', 'lib', 'builtins', 'placeholder', 'Example.svelte'), 'utf8');
  const reg = panelRegistry(readFileSync(join(dir, 'panels.js'), 'utf8'));
  const lines = [];
  const dirLines = [];
  const idLines = [];
  for (const { id, file } of reg) {
    idLines.push(`  ${JSON.stringify(id)},`);
    const text = readFileSync(resolve(dir, file), 'utf8');
    lines.push(`  ${JSON.stringify(id)}: ${JSON.stringify(text)},`);
    // The panel's directory, frontend-relative: a built-in's relative imports
    // resolve against it (compile.js BUILTIN_HELPERS).
    const panelDir = 'src/lib/builtins/' + file.replace(/^\.\//, '').replace(/\/[^/]+$/, '');
    dirLines.push(`  ${JSON.stringify(id)}: ${JSON.stringify(panelDir)},`);
  }
  return [
    '// GENERATED by frontend/scripts/gen-builtin-sources.mjs. Do not edit.',
    '// The Svelte source of each compiled builtin panel, keyed by builtin id,',
    '// the directory each source lives in (frontend-relative), and the ids in',
    '// registry order (builtins/panels.js BUILTIN_PANELS).',
    'export const PANEL_IDS = Object.freeze([',
    ...idLines,
    ']);',
    'export const PANEL_SOURCES = Object.freeze({',
    ...lines,
    '});',
    'export const PLACEHOLDER_SOURCE = ' + JSON.stringify(placeholder) + ';',
    'export const PANEL_DIRS = Object.freeze({',
    ...dirLines,
    '});',
    '',
  ].join('\n');
}

// Run as a script: write the module.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, generate());
  console.log(`gen-builtin-sources: wrote ${OUT_FILE}`);
}
